#!/usr/bin/env python3
"""Generate one source for both the native bridge and the CoreAudio HAL bundle."""
from pathlib import Path
import argparse
import re
ROOT=Path(__file__).resolve().parents[1]
def expand(path,seen):
    path=path.resolve()
    if path in seen:return '/* already included: '+str(path.relative_to(ROOT))+' */\n'
    seen.add(path)
    def include(match):
        local=(path.parent/match.group(1)).resolve()
        if not local.is_relative_to(ROOT):raise ValueError(local)
        return expand(local,seen)
    return '/* BEGIN '+str(path.relative_to(ROOT))+' */\n'+re.sub(r'^\s*#(?:include|import) "([^"\n]+)"\s*$',include,path.read_text(),flags=re.M)+'\n'
def generated():
    return '''/* GENERATED by automation/generate_bridge.py. SPDX-License-Identifier: GPL-2.0-or-later
 * One source, two binaries: native MIDI/audio bridge and CoreAudio HAL plug-in.
 * Bridge: compile as Objective-C (-x objective-c -fobjc-arc -fblocks).
 * HAL: compile as C with -DKORE_HAL_PLUGIN -bundle. See Makefile.
 * Public IOUSBHost APIs require Objective-C even though this file has a .c suffix.
 */
#ifdef KORE_HAL_PLUGIN
'''+expand(ROOT/'coreaudio/plugin.c',set())+'\n#else\n'+expand(ROOT/'audio/bridge_main.m',set())+'\n#endif\n'
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    target=ROOT/'kore1-final-bridge.c';s=generated()
    if a.check:
        if not target.exists() or target.read_text()!=s:raise SystemExit('Generated bridge is stale: run python3 automation/generate_bridge.py')
        print('Standalone native bridge and HAL source matches maintained sources')
    else:target.write_text(s)
