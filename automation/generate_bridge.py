#!/usr/bin/env python3
"""Generate a standalone C translation unit from the maintained diagnostic bridge."""
from pathlib import Path
import argparse
ROOT = Path(__file__).resolve().parents[1]

def generated():
    source = (ROOT / 'kore1-bridge-audio.c').read_text()
    header = (ROOT / 'audio/caiaq.h').read_text()
    assert source.count('#include "audio/caiaq.h"') == 1
    return ('/* GENERATED by automation/generate_bridge.py; edit the original sources.\n'
            ' * macOS CoreMIDI + experimental libusb audio bridge.\n'
            ' * Not a production CoreAudio driver. Native audio is a separate executable.\n'
            ' * Build: make bridge (requires libusb-1.0 and pkg-config).\n'
            ' * SPDX-License-Identifier: GPL-2.0-or-later\n */\n' +
            source.replace('#include "audio/caiaq.h"', header.rstrip()))

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'kore1-final-bridge.c'
    if args.check:
        if not target.exists() or target.read_text() != generated():
            raise SystemExit('Generated bridge is stale: run python3 automation/generate_bridge.py')
        print('Standalone bridge matches maintained sources')
    else:
        target.write_text(generated())
